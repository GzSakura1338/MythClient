// Read Lunar's KIN v1 mapping catalog. No game process is modified.
using System;
using System.IO;
using System.IO.Compression;
using System.Text;
using System.Collections.Generic;
using System.Text.RegularExpressions;
using System.Linq;

public sealed class LunarMappingTool
{
    public sealed class Member { public string Owner, Name, Descriptor, Target; public bool Method; }
    public readonly Dictionary<string,string> Classes = new Dictionary<string,string>();
    public readonly List<Member> Members = new List<Member>();
    BinaryReader reader;
    int Int() { var b=reader.ReadBytes(4); if(b.Length!=4) throw new EndOfStreamException(); return (b[0]<<24)|(b[1]<<16)|(b[2]<<8)|b[3]; }
    string Utf() { int n=(reader.ReadByte()<<8)|reader.ReadByte(); var b=reader.ReadBytes(n); if(b.Length!=n) throw new EndOfStreamException(); return Encoding.UTF8.GetString(b); }
    void Class(string parentSource, string parentTarget)
    {
        string source=Utf(), target=Utf();
        if(parentSource!=null) { source=parentSource+"$"+source; target=parentTarget+"$"+target; }
        Classes.Add(source,target);
        int children=Int();
        if(children<0||children>10000) throw new InvalidDataException("children "+source+" at "+reader.BaseStream.Position);
        for(int i=0;i<children;i++) Class(source,target);
        for(int kind=0;kind<2;kind++) {
            int count=Int();
            if(count<0||count>100000) throw new InvalidDataException("members "+source+" at "+reader.BaseStream.Position);
            for(int i=0;i<count;i++) Members.Add(new Member{Owner=source,Name=Utf(),Descriptor=Utf(),Target=Utf(),Method=kind==1});
        }
    }
    public static LunarMappingTool Read(string jar)
    {
        var tool=new LunarMappingTool();
        using(var zip=ZipFile.OpenRead(jar)) using(var data=new MemoryStream()) {
            using(var stream=zip.GetEntry("lunar/lunar2intermediary_1.21.11.kin").Open()) stream.CopyTo(data);
            data.Position=0; tool.reader=new BinaryReader(data);
            if(tool.Int()!=0x05e8f046||tool.reader.ReadByte()!=1) throw new InvalidDataException("KIN header");
            if(tool.Int()!=0) throw new InvalidDataException("Unexpected KIN metadata");
            int count=tool.Int(); for(int i=0;i<count;i++) tool.Class(null,null);
            if(data.Position!=data.Length) throw new InvalidDataException("Unread KIN bytes: "+(data.Length-data.Position));
        }
        return tool;
    }
    public string Descriptor(string value) { return Regex.Replace(value,@"L([^;]+);",m=>"L"+(Classes.TryGetValue(m.Groups[1].Value,out var name)?name:m.Groups[1].Value)+";"); }
    public void Generate(string sourceRoot,string output)
    {
        var literals=new HashSet<string>(); var owners=new HashSet<string>();
        foreach(var file in Directory.EnumerateFiles(sourceRoot,"*",SearchOption.AllDirectories)) {
            if(Path.GetFileName(file).Equals("Lunar12111.inc",StringComparison.OrdinalIgnoreCase)||!new[]{".cpp",".h",".inc"}.Contains(Path.GetExtension(file))) continue;
            string text=File.ReadAllText(file);
            foreach(Match m in Regex.Matches(text,"\"([^\"\r\n]+)\"")) literals.Add(m.Groups[1].Value);
            foreach(Match m in Regex.Matches(text,@"(?:net[./]minecraft|com[./]mojang)[./][\w.$/]+")) owners.Add(m.Value.Replace('.','/'));
        }
        var lines=new List<string>{"// Generated by Client/tools/lunar12111/generate.ps1 from Lunar KIN v1.",
            "// Minecraft 1.21.11 Mojang names -> Lunar Fabric intermediary.",
            "// Class catalog is complete; members include source-referenced owners/names and inherited bindings.",
            "#if defined(NOVA_LUNAR12111_CLASS)"};
        foreach(var c in Classes.OrderBy(p=>p.Key,StringComparer.Ordinal))
            lines.Add("NOVA_LUNAR12111_CLASS(\""+c.Key.Replace('/','.')+"\", \""+c.Value.Replace('/','.')+"\")");
        lines.Add("#elif defined(NOVA_LUNAR12111_MEMBER)");
        foreach(var m in Members.Where(m=>owners.Contains(m.Owner)&&literals.Contains(m.Name)).OrderBy(m=>m.Owner+"|"+m.Name+"|"+m.Descriptor,StringComparer.Ordinal))
            lines.Add("NOVA_LUNAR12111_MEMBER(\""+m.Owner.Replace('/','.')+"\", \""+m.Name+"\", \""+m.Descriptor+"\", \""+m.Target+"\")");
        lines.Add("#else\n#error \"Select a Lunar12111 mapping section\"\n#endif");
        File.WriteAllLines(output,lines,new UTF8Encoding(false));
    }
}
