inline std::string Remap(std::string_view value,Build build=activeBuild.load()) {
    if(build!=Build::September30&&build!=Build::October2)return std::string(value);
    std::string out;out.reserve(value.size());
    // Consume the source once: never cascade a replacement into another mapping.
    for(size_t i=0;i<value.size();) {
        bool matched=false;
        if(build==Build::October2)for(const auto& entry:October2Names)if(value.substr(i,entry.before.size())==entry.before){
            out+=entry.after;i+=entry.before.size();matched=true;break;
        }
        if(!matched)for(const auto& entry:September30Names)if(value.substr(i,entry.before.size())==entry.before){
            out+=entry.after;i+=entry.before.size();matched=true;break;
        }
        if(!matched)out+=value[i++];
    }
    return out;
}
