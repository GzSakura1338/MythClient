"""Build the embedded Classic font from a local 1.8.9 font atlas; writes no game files.

Run with Pillow and fontTools available. The resulting small TTF contains ASCII
and the heart glyph; Nova merges its existing HUD font for other characters.
"""
from pathlib import Path
from io import BytesIO
import sys
import zipfile

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'Client/build-vs2026/font-tools'))
from PIL import Image
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

source = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / 'AppData/Roaming/.minecraft/versions/1.8.9/1.8.9.jar'
with zipfile.ZipFile(source) as archive:
    ascii_image = Image.open(BytesIO(archive.read('assets/minecraft/textures/font/ascii.png'))).convert('RGBA')
    unicode_image = Image.open(BytesIO(archive.read('assets/minecraft/textures/font/unicode_page_27.png'))).convert('RGBA')
    sizes = archive.read('assets/minecraft/font/glyph_sizes.bin')

unit = 128
font = FontBuilder(9 * unit, isTTF=True)
glyphs, metrics, cmap = {}, {}, {}
glyphs['.notdef'] = TTGlyphPen(None).glyph()
metrics['.notdef'] = (6 * unit, 0)
for code in [*range(32, 127), 0x2764]:
    name = f'uni{code:04X}'
    pen = TTGlyphPen(None)
    if code < 127:
        tile = ascii_image.crop((code % 16 * 8, code // 16 * 8, code % 16 * 8 + 8, code // 16 * 8 + 8))
        step, left = unit, 0
        right = max((x for x in range(8) for y in range(8) if tile.getpixel((x, y))[3]), default=-1)
        advance = 4 * unit if code == 32 else (right + 2) * unit
    else:
        tile = unicode_image.crop((4 * 16, 6 * 16, 5 * 16, 7 * 16))
        left, right = sizes[code] >> 4, sizes[code] & 15
        step = unit // 2
        advance = (right - left + 1) * step + unit
    for y in range(tile.height):
        x = left
        while x <= right:
            if tile.getpixel((x, y))[3] < 128:
                x += 1
                continue
            start = x
            while x <= right and tile.getpixel((x, y))[3] >= 128:
                x += 1
            x0, x1 = (start - left) * step, (x - left) * step
            y0, y1 = 8 * unit - (y + 1) * step, 8 * unit - y * step
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    glyphs[name], metrics[name], cmap[code] = pen.glyph(), (advance, 0), name
font.setupGlyphOrder(list(glyphs))
font.setupCharacterMap(cmap)
font.setupGlyf(glyphs)
font.setupHorizontalMetrics(metrics)
font.setupHorizontalHeader(ascent=8 * unit, descent=-unit)
font.setupOS2(sTypoAscender=8 * unit, sTypoDescender=-unit, usWinAscent=8 * unit, usWinDescent=unit)
font.setupNameTable({'familyName': 'Nova Classic', 'styleName': 'Regular', 'uniqueFontIdentifier': 'NovaClassic',
    'fullName': 'Nova Classic', 'psName': 'NovaClassic'})
font.setupPost()
font.font['head'].created = font.font['head'].modified = 3406620153
data = BytesIO(); font.save(data); binary = data.getvalue()
header = '// Generated by tools/generate-classic-font.py from the local Minecraft 1.8.9 atlas.\n#pragma once\n'
header += 'inline constexpr unsigned char ClassicFontData[] = {\n'
header += '\n'.join('    ' + ','.join(f'0x{v:02X}' for v in binary[i:i+24]) + ',' for i in range(0, len(binary), 24))
header += '\n};\n'
(root / 'Client/src/ui/clickgui/fonts/font_classic.h').write_text(header, encoding='utf-8')
out = root / 'Client/build-vs2026/classic-font'
out.mkdir(parents=True, exist_ok=True)
(out / 'classic.ttf').write_bytes(binary)
print(f'Classic font generated: {len(cmap)} glyphs, {len(binary)} bytes')
